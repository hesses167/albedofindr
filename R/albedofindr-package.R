#' albedofindr: A package that calculates albedo
#'
#' This package is performs narrow-to-broadband conversion
#' and calculates albedo for Landsat 5, 7, and 8, which
#' do not have a native albedo product.
#'
#' @docType _PACKAGE
#' @name albedofindr-package
#' @section Functions:
#' \describe{
#'    \item{\code{get_collection}}{Determine which Landsat version - 5, 7, or 8 - should be used based on
#'    collection year, then retrieve corresponding Landsat collection}
#'    \item{\code{calcalbedo_L57}}{Calculate albedo based on Liang et al, 2001's linear regression, for Landsat 5 and 7, mask clouds}
#'    \item{\code{calcalbedo_L8}}{Calculate albedo as in calcalbedo_L57, but replace B1 with B2 for Landsat 8, mask clouds}
#'    \item{\code{get_albedo_collection}}{Calculate albedo for each image in collection}
#'    \item{\code{get_median_albedo}}{Calculate a median albedo composite for dates chosen by user}
#' }
#'
#' @section Data:
#' \describe{
#'    \item{\code{sample_polygon_1995}}{Sample polygon for a 1995 wildfire, sourced from National Burned Area Composite}
#'    \item{\code{median_albedo_1995fireyear_1997img}}{Median albedo composite as generated by albedofindr, through GEE}
#' }
#' @author Sara Hesse, PhD student, School of Earth, Environment and Society, McMaster University \email{hesses@@mcmaster.ca}
#' @references \url{https://github.com/hesses167/albedofindr}
NULL
